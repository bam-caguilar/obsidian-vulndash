test('DailyRollupNoteWriter creates a new rollup note when one does not exist', async () => {
  const vault = new InMemoryRollupVault();
  const writer = new DailyRollupNoteWriter(vault);

  const result = await writer.write({
    date: '2026-04-18',
    document: createRenderedDocument(),
    folderPath: 'briefings/daily'
  });

  assert.equal(result.created, true);
  assert.equal(result.path, 'briefings/daily/VulnDash Briefing 2026-04-18.md');
  assert.deepEqual(vault.createdFolders, ['briefings', 'briefings/daily']);
  assert.deepEqual(vault.createdFiles, ['briefings/daily/VulnDash Briefing 2026-04-18.md']);
  assert.equal(vault.get(result.path), result.content);
});

test('DailyRollupNoteWriter updates an existing rollup note while preserving analyst notes', async () => {
  const notePath = 'briefings/daily/VulnDash Briefing 2026-04-18.md';
  const vault = new InMemoryRollupVault(new Map<string, string>([
    ['briefings', '__folder__'],
    ['briefings/daily', '__folder__'],
    [notePath, [
      '# VulnDash Briefing 2026-04-18',
      '',
      '## Analyst Notes',
      '',
      '- Existing analyst note',
      '',
      '<!-- VULNDASH:SECTION daily-rollup START -->',
      'Old content',
      '<!-- VULNDASH:SECTION daily-rollup END -->'
    ].join('\n')]
  ]));
  const writer = new DailyRollupNoteWriter(vault);

  const result = await writer.write({
    date: '2026-04-18',
    document: createRenderedDocument(),
    folderPath: 'briefings/daily'
  });

  assert.equal(result.created, false);
  assert.deepEqual(vault.createdFiles, []);
  assert.deepEqual(vault.writes, [notePath]);
  assert.match(result.content, /Existing analyst note/);
  assert.match(result.content, /Critical issue/);
});

test('DailyRollupGenerator filters findings for a single-project briefing before rendering', async () => {
  const findings: RollupFinding[] = [
    createFinding(),
    createFinding({
      affectedProjects: [{
        displayName: 'Identity API',
        notePath: 'Projects/Identity.md',
        sourceSbomIds: ['sbom-identity'],
        sourceSbomLabels: ['identity-api.spdx.json'],
        status: 'linked'
      }],
      key: 'NVD:CVE-2026-4001',
      vulnerability: {
        affectedProducts: [],
        cvssScore: 9.1,
        hydrationState: 'complete',
        id: 'CVE-2026-4001',
        publishedAt: '2026-04-18T00:00:00.000Z',
        references: [],
        severity: 'CRITICAL',
        source: 'NVD',
        summary: 'Summary',
        title: 'Identity finding',
        updatedAt: '2026-04-18T00:00:00.000Z'
      }
    })
  ];
  const selector = {
    execute: () => findings
  } as unknown as SelectRollupFindings;
  let renderedFindings: readonly RollupFindingProjection[] = [];
  let renderedMatchedComponentCount = 0;
  let renderedScopeLabel = '';
  const rendered: RenderedDailyRollup = {
    analystNotesHeading: '## Analyst Notes',
    analystNotesPlaceholder: '- Placeholder',
    fileName: 'VulnDash Briefing 2026-04-18 - Portal Web.md',
    managedSections: [],
    title: '# VulnDash Briefing 2026-04-18 - Portal Web'
  };
  const renderer = {
    render: (input: { readonly findings: readonly RollupFindingProjection[]; readonly scope: { readonly displayLabel: string; }; }) => {
      renderedFindings = input.findings;
      renderedMatchedComponentCount = input.findings[0]?.matchedComponents.length ?? 0;
      renderedScopeLabel = input.scope.displayLabel;
      return rendered;
    }
  } as unknown as RollupMarkdownRenderer;
  const writer: DailyRollupWriter = {
    write: async () => ({
      content: rendered.title,
      created: true,
      path: 'VulnDash Briefings/VulnDash Briefing 2026-04-18 - Portal Web.md'
    })
  };

  await new DailyRollupGenerator(selector, renderer, writer, {
    execute: async (_taskKind: 'render-daily-rollup', payload: { readonly findings: readonly RollupFindingProjection[]; readonly scope: { readonly displayLabel: string; }; }) => ({
      document: renderer.render(payload as never)
    })
  } as never).execute({
    affectedProjectsByVulnerabilityRef: new Map(),
    date: '2026-04-18',
    projects,
    relationshipGraph: emptyRelationshipGraph,
    scope: {
      projectId: 'project::portal-web',
      type: 'single-project'
    },
    settings,
    sboms,
    triageByCacheKey: new Map(),
    vulnerabilities: []
  });

  assert.equal(renderedScopeLabel, 'Portal Web');
  assert.deepEqual(renderedFindings.map((finding) => finding.vulnerability.id), ['CVE-2026-4000']);
  assert.equal(renderedMatchedComponentCount, 0);
});

