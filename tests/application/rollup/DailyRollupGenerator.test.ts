test('DailyRollupGenerator orchestrates selection, rendering, and writing', async () => {
  const findings: RollupFinding[] = [];
  const calls: string[] = [];
  const selector = {
    execute: (input: { readonly date?: string; }) => {
      calls.push('select');
      assert.equal(input.date, undefined);
      return findings;
    }
  } as unknown as SelectRollupFindings;
  const rendered: RenderedDailyRollup = {
    analystNotesHeading: '## Analyst Notes',
    analystNotesPlaceholder: '- Placeholder',
    fileName: 'VulnDash Briefing 2026-04-18.md',
    managedSections: [],
    title: '# VulnDash Briefing 2026-04-18'
  };
  const renderer = {
    render: (input: { readonly date: string; readonly findings: readonly RollupFindingProjection[]; readonly scope: { readonly displayLabel: string; }; }) => {
      calls.push('render-fallback');
      assert.equal(input.date, '2026-04-18');
      assert.equal(input.findings.length, findings.length);
      assert.equal(input.scope.displayLabel, 'All Projects');
      return rendered;
    }
  } as unknown as RollupMarkdownRenderer;
  const writer: DailyRollupWriter = {
    write: async (input) => {
      calls.push('write');
      assert.equal(input.date, '2026-04-18');
      assert.equal(input.document, rendered);
      assert.equal(input.folderPath, 'VulnDash Briefings');
      return {
        content: '# VulnDash Briefing 2026-04-18',
        created: true,
        path: 'VulnDash Briefings/VulnDash Briefing 2026-04-18.md'
      };
    }
  };
  const asyncTaskCoordinator = {
    execute: async (_taskKind: 'render-daily-rollup', payload: { readonly date: string; readonly findings: readonly RollupFindingProjection[]; }) => {
      calls.push('render');
      assert.equal(payload.date, '2026-04-18');
      assert.equal(payload.findings.length, findings.length);
      return {
        document: rendered
      };
    }
  };

  const result = await new DailyRollupGenerator(selector, renderer, writer, asyncTaskCoordinator as never).execute({
    affectedProjectsByVulnerabilityRef: new Map(),
    date: '2026-04-18',
    projects: [],
    relationshipGraph: emptyRelationshipGraph,
    scope: ALL_PROJECTS_BRIEFING_SCOPE,
    settings,
    sboms: [],
    triageByCacheKey: new Map(),
    vulnerabilities: []
  });

  assert.deepEqual(calls, ['select', 'render', 'write']);
  assert.equal(result.findingsCount, 0);
  assert.equal(result.path, 'VulnDash Briefings/VulnDash Briefing 2026-04-18.md');
});

class InMemoryRollupVault implements DailyRollupVaultAdapter {
  public readonly createdFiles: string[] = [];
  public readonly createdFolders: string[] = [];
  public readonly writes: string[] = [];

  public constructor(
    private readonly entries = new Map<string, string>()
  ) {}

  public async create(path: string, content: string): Promise<void> {
    this.createdFiles.push(path);
    this.entries.set(path, content);
  }

  public async createFolder(path: string): Promise<void> {
    this.createdFolders.push(path);
    this.entries.set(path, '__folder__');
  }

  public async exists(path: string): Promise<boolean> {
    return this.entries.has(path);
  }

  public async read(path: string): Promise<string> {
    const content = this.entries.get(path);
    if (content === undefined) {
      throw new Error('ENOENT');
    }

    return content;
  }

  public async write(path: string, content: string): Promise<void> {
    this.writes.push(path);
    this.entries.set(path, content);
  }

  public get(path: string): string | undefined {
    return this.entries.get(path);
  }
}

